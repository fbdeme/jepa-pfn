"""Stratify the classification accuracy gap to HistGB by class count / feature count / row count for the 180k snapshot
(real prior, dual_split), real_ds 20k (real prior, ds) and base_ds 20k (paper prior, ds) on the 115 shared datasets.
All numbers from the suite JSONs; writes results_strata.json + strata.md (docs/prior_v2_plan.md section 1).
Run: uv run python eval/prior_ladder_2026-09-10/strata.py"""
import json, statistics as st
from pathlib import Path
R = Path(__file__).resolve().parents[2]
L = json.load(open(R/'eval/results_suite_real_long180k.json'))
F = json.load(open(R/'eval/results_suite_full.json'))
RD = json.load(open(R/'eval/results_suite_real_ds.json'))
census = {r['name']: r for r in json.load(open(R/'eval/results_realdata_shapes.json'))['rows']}
ncls = {r['key']: r['n_classes'] for r in json.load(open(R/'eval/results_class_count_census.json'))['datasets']}
SNAP = [k for k in next(iter(L.values())) if k.startswith('v4_')][0]
def ds_key(d, name):
    for k in d:
        if k.split('|')[1] == name and k.endswith('clf'): return k
    return None
rows = []
for k, v in L.items():
    if not k.endswith('|clf'): continue
    name = k.split('|')[1]
    fk = ds_key(F, name); rk = ds_key(RD, name)
    if fk is None or rk is None: continue
    fm = F[fk].get('models', F[fk]); rm = RD[rk].get('models', RD[rk])
    bd = [m for m in fm if 'base_ds' in m]; rd = [m for m in rm if 'real_ds' in m]
    if not bd or not rd: continue
    c = census.get(name, {})
    rows.append(dict(name=name, ncls=ncls.get(k), nfeat=c.get('n_features'), nrows=c.get('n_rows'),
        snap=v[SNAP]['acc'], hgb=v['histgb']['acc'],
        base_ds=st.mean(fm[m]['acc'] for m in bd), hgb_paper=fm['histgb']['acc'],
        real_ds=st.mean(rm[m]['acc'] for m in rd)))
print('n', len(rows), 'base_ds models used e.g.', bd, 'real_ds', rd)
OUT = {}
MD = ['<!-- generated by eval/prior_ladder_2026-09-10/strata.py from the suite JSONs -->', '| stratum | n | 180k snapshot (real prior, latent) | real_ds 20k (real prior, ds) | base_ds 20k (paper prior, ds) | HistGB | gap 180k | gap base_ds |', '|---|---|---|---|---|---|---|---|']
def strata(fn, labels):
    for lab, pred in labels:
        g = [r for r in rows if r[fn] is not None and pred(r[fn])]
        if not g: continue
        m = lambda key: st.mean(r[key] for r in g)
        rec = dict(n=len(g), snap180k=m('snap'), real_ds20k=m('real_ds'), base_ds20k=m('base_ds'), histgb=m('hgb'), histgb_paper_pass=m('hgb_paper'),
                   gap_snap=m('hgb') - m('snap'), gap_base_ds=m('hgb_paper') - m('base_ds'))
        OUT[f"{fn}={lab}"] = rec
        print(f"{fn}={lab:>8} n={len(g):3d}  snap180k {m('snap'):.3f}  real_ds20k {m('real_ds'):.3f}  base_ds20k {m('base_ds'):.3f}  histgb {m('hgb'):.3f}  | gap snap {rec['gap_snap']:+.3f} base_ds {rec['gap_base_ds']:+.3f}")
        MD.append(f"| {fn} {lab} | {len(g)} | {m('snap'):.3f} | {m('real_ds'):.3f} | {m('base_ds'):.3f} | {m('hgb'):.3f} | {rec['gap_snap']:+.3f} | {rec['gap_base_ds']:+.3f} |")
strata('ncls', [('2', lambda x: x==2), ('3-5', lambda x: 3<=x<=5), ('6-10', lambda x: 6<=x<=10)])
strata('nfeat', [('<=16', lambda x: x<=16), ('17-64', lambda x: 17<=x<=64), ('>64', lambda x: x>64)])
strata('nrows', [('<=1024', lambda x: x<=1024), ('1k-10k', lambda x: 1024<x<=10000), ('>10k', lambda x: x>10000)])


D = Path(__file__).parent
json.dump(dict(note="115 classification datasets shared by results_suite_real_long180k / results_suite_full / results_suite_real_ds; base_ds pass = K_FEAT 32 / CTX 512, others K_FEAT 64 / CTX 1024; histgb column = the 180k pass, histgb_paper_pass = the base_ds pass",
               strata=OUT, datasets=rows), open(D / 'results_strata.json', 'w'), indent=1)
(D / 'strata.md').write_text('\n'.join(MD) + '\n')
print('wrote', D / 'results_strata.json', D / 'strata.md')
